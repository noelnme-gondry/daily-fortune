export function periodOutlook(kind, ranked, rhythm, label) {
  const top = ranked[0], low = ranked[ranked.length - 1];
  const opening = kind === 'week' ? rhythms[rhythm] : kind === 'month' ? `${label}에는` : kind === 'year' ? `${label}에는` : '';
  if (top.score === low.score) return [opening, '한 가지 운만 유난히 두드러지지는 않아요. 평소 마음을 두었던 일부터 살펴보세요.'].filter(Boolean).join(' ');
  const copy = kind === 'year' ? annualThemes : kind === 'month' ? monthly : areas;
  const lead = top.score >= 60 ? copy[top.key][0] : copy[low.key][1];
  const care = top.score >= 60 && low.score < 60 ? copy[low.key][1] : '';
  return [opening, lead, care].filter(Boolean).join(' ');
}
